const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = __dirname;
const v = '4.2.6';
const source = fs.readFileSync(path.join(root,'dist/index.js'),'utf8');
const plugin = JSON.parse(fs.readFileSync(path.join(root,'plugin.json')));
const npm = JSON.parse(fs.readFileSync(path.join(root,'package.json')));
const pack = JSON.parse(fs.readFileSync(path.join(root,'visualizer-packs/arcade/manifest.json')));
const backend = fs.readFileSync(path.join(root,'main.py'),'utf8');
assert.equal(plugin.version,v,'Decky plugin version');
assert.equal(npm.version,v,'npm version');
assert.equal(pack.version,v,'Arcade manifest version');
assert(source.includes(`const GTM_VERSION = "${v}";`),'frontend version');
assert(backend.includes(`getattr(decky, "DECKY_PLUGIN_VERSION", "${v}")`),'backend fallback');
assert(source.includes('`PREVIEW · v${GTM_VERSION}`'),'main brand banner must show Preview + version');
assert(source.includes('`Game Theme Music v${GTM_VERSION} · Preview · Six Built-in Arcade Games`'),'footer must show live version');
assert(source.includes('`v${GTM_VERSION} · Preview`'),'identity header must show Preview version');
assert(!source.includes("'Game Theme Music 4.2.0 · Preview · Built-in Arcade'"),'stale 4.2.0 footer');
assert(source.includes('world_arcade_neon_strike_gallery'),'retained arcade games');
console.log('PASS 4.2.6 version consistency: metadata + banner + footer + identity + backend + Arcade manifest');
